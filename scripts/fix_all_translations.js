function containsChinese(str) {
  if (typeof str !== 'string') return false;
  return /[\u4e00-\u9fff]/.test(str);
}

function replaceChineseWithEnglish(targetObj, sourceEnObj) {
  for (const key in targetObj) {
    if (typeof targetObj[key] === 'object' && targetObj[key] !== null) {
      if (sourceEnObj[key]) {
        replaceChineseWithEnglish(targetObj[key], sourceEnObj[key]);
      }
    } else if (typeof targetObj[key] === 'string' && containsChinese(targetObj[key])) {
      if (sourceEnObj[key]) {
        targetObj[key] = sourceEnObj[key];
      }
    }
  }
}

