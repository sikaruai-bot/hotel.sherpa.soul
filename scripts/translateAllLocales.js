let updatedCount = 0;

Object.keys(langFileMap).forEach((langCode) => {
  const fileName = langFileMap[langCode];
  const filePath = path.join(localesDir, fileName);

  if (fs.existsSync(filePath)) {
    try {
      const content = JSON.parse(fs.readFileSync(filePath, 'utf8'));
      const transObj = bookNowPageTranslations[langCode] || bookNowPageTranslations['en'];
      const modalTransObj = bookingModalTranslations[langCode] || bookingModalTranslations['en'];
      
      content.bookNowPage = transObj;
      content.bookingModal = modalTransObj;

      fs.writeFileSync(filePath, JSON.stringify(content, null, 2), 'utf8');
      console.log(`Updated ${fileName} with bookNowPage and bookingModal translations.`);
      updatedCount++;
    } catch (e) {
      console.error(`Error updating ${fileName}:`, e);
    }
  } else {
    console.warn(`File ${fileName} not found at ${filePath}`);
  }
});

console.log(`\nSuccessfully updated ${updatedCount} locale files with full translations!`);

